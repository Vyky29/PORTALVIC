#!/usr/bin/env node
/**
 * Build working_ui/splash.html from live WordPress page,
 * removing Wed Acton Multi-Activity blocks (no Elementor access needed).
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

const SOURCE = "https://www.clubsensational.org/splash/";
const OUT = resolve(process.cwd(), "working_ui/splash.html");

function removeTopSectionByDataId(html, dataId) {
  const needle = `data-id="${dataId}"`;
  let from = 0;
  let out = html;
  while (true) {
    const idx = out.indexOf(needle, from);
    if (idx === -1) break;
    const start = out.lastIndexOf("<section", idx);
    if (start === -1) break;
    let pos = start;
    let depth = 0;
    let end = -1;
    while (pos < out.length) {
      const open = out.indexOf("<section", pos);
      const close = out.indexOf("</section>", pos);
      if (close === -1) break;
      if (open !== -1 && open < close) {
        depth += 1;
        pos = open + 8;
        continue;
      }
      depth -= 1;
      pos = close + 10;
      if (depth === 0) {
        end = pos;
        break;
      }
    }
    if (end === -1) break;
    out = out.slice(0, start) + out.slice(end);
    from = start;
  }
  return out;
}

function cleanFooterCopy(html) {
  return html
    .replace(
      /<b>Tuesday,\s*Wednesday\s*&\s*Thursday<\/b><\/br>\s*Afternoon<\/br><\/br>\s*/gi,
      "",
    )
    .replace(/<\/br>\s*&<\/br>\s*W3 6NE/gi, "")
    .replace(
      /<link rel="canonical" href="[^"]*"/,
      '<link rel="canonical" href="https://www.clubsensational.org/splash/"',
    );
}

const res = await fetch(SOURCE, { redirect: "follow" });
if (!res.ok) throw new Error(`Fetch failed: ${res.status}`);
let html = await res.text();

html = removeTopSectionByDataId(html, "ffc7ab4");
html = removeTopSectionByDataId(html, "cb0281b");
html = cleanFooterCopy(html);

const banner =
  "<!-- Generated by scripts/build-splash-page.mjs — Wed Acton Multi-Activity removed -->\n";
writeFileSync(OUT, banner + html, "utf8");
console.log(`Wrote ${OUT} (${html.length} bytes)`);
